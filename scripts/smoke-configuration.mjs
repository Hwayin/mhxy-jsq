async function choose(label, values, multiple = false) {
  await selectedField(label).click()
  for (const value of values) {
    if (value !== '未配置 / 清空') {
      await page.locator('.choice-search input').fill(value)
      await page.locator('.choice-row').filter({ has: page.getByText(value, { exact: true }) }).first().waitFor()
    }
    await page.locator('.choice-row').getByText(value, { exact: true }).first().click()
  }
  if (multiple) await page.locator('.choice-panel .primary').click()
}
