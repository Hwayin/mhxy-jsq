async function importFile(target, file) {
  const chooser = target.waitForEvent('filechooser')
  await target.getByText('从 JSON 文件导入', { exact: true }).click()
  await (await chooser).setFiles(file)
  await target.getByText('导入角色备份？', { exact: true }).waitFor()
  await target.getByText('确定', { exact: true }).click()
  await target.getByText('1 个账号 · 1 个角色 · 10 笔明细', { exact: true }).waitFor()
}
