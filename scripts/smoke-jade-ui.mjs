async function screenshot(name) { await page.locator('uni-toast').last().waitFor({ state: 'hidden' }); await page.evaluate(() => { scrollTo(0, 0); for (const el of document.querySelectorAll('*')) if (el.scrollTop > 0) el.scrollTop = 0 }); await page.screenshot({ path: fileURLToPath(new URL('jade-' + name + '.png', images)) }) }
