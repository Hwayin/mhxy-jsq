import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { pathToFileURL, fileURLToPath } from 'node:url'
import { ledger } from './load-ledger.mjs'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:5178'
const failures = []
const images = new URL('../unpackage/school-verification/', import.meta.url)
await mkdir(images, { recursive: true })

try {
  for (const width of [390, 320]) {
    const context = await browser.newContext({ viewport: { width, height: 844 } })
    const page = await context.newPage()
    page.setDefaultTimeout(15000)
    page.on('pageerror', error => failures.push(error.message))
    const group = label => page.locator('.field-group').filter({ has: page.getByText(label, { exact: true }), hasNot: page.locator('.field-group') })
    const school = () => group('门派 *').locator('.field')
    const picker = () => page.locator('.choice-overlay')
    const editRole = async () => {
      await page.locator('.role-menu').click()
      await page.getByText('编辑角色 / 换算设置', { exact: true }).click()
    }
    const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('mhxy-ledger-v1')))
    const openSchool = async () => {
      await school().click()
      await picker().getByText('选择门派', { exact: true }).waitFor()
      assert.equal(await picker().getByText('未配置 / 清空', { exact: true }).count(), 0)
    }
    const selectSchool = async value => {
      await openSchool()
      await picker().locator('.choice-search input').fill(value)
      await picker().locator('.choice-row').getByText(value, { exact: true }).click()
      await picker().waitFor({ state: 'hidden' })
      assert.match(await school().innerText(), new RegExp(value))
    }
    await page.goto(base)
    await page.getByText('成本总览', { exact: true }).waitFor()
    const seed = ledger.demoLedger()
    await page.evaluate(seed => localStorage.setItem('mhxy-ledger-v1', JSON.stringify(seed)), seed)
    await page.reload()
    await page.getByText('账号', { exact: true }).click()
    await page.getByText('＋ 添加角色', { exact: true }).first().click()
    await page.getByText('新增角色', { exact: true }).first().waitFor()
    await group('角色名称 *').locator('input').fill('门派验证角色')
    await group('服务器 *').locator('input').fill('验证服务器')
    await openSchool()
    assert.equal(await picker().locator('.choice-row').count(), ledger.SCHOOLS.length)
    const before = await read()
    await picker().getByText('取消', { exact: true }).click()
    assert.match(await school().innerText(), /大唐官府/)
    assert.deepEqual(await read(), before)
    for (const value of ledger.SCHOOLS) await selectSchool(value)
    assert.equal(await group('角色名称 *').locator('input').inputValue(), '门派验证角色')
    assert.equal(await group('服务器 *').locator('input').inputValue(), '验证服务器')
    await selectSchool('九黎城')
    await openSchool()
    await picker().locator('.choice-row').getByText('其他', { exact: true }).click()
    assert.match(await school().innerText(), /其他/)
    await selectSchool('普陀山')
    await openSchool()
    assert.match(await picker().locator('.choice-selected').innerText(), /普陀山/)
    await picker().locator('.choice-search input').fill('不存在的门派')
    await picker().getByText('没有找到匹配选项', { exact: true }).waitFor()
    await picker().getByText('取消', { exact: true }).click()
    assert.match(await school().innerText(), /普陀山/)
    assert.deepEqual(await read(), before)
    await page.getByText('保存记录', { exact: true }).click()
    await page.getByText('我的账号', { exact: true }).waitFor()
    const saved = (await read()).roles.find(role => role.name === '门派验证角色')
    assert.equal(saved.school, '普陀山')
    assert.equal(saved.purchaseCents, 0)
    assert.deepEqual((await read()).assets, seed.assets)
    await page.getByText('门派验证角色', { exact: true }).click()
    await editRole()
    await openSchool()
    assert.match(await picker().locator('.choice-selected').innerText(), /普陀山/)
    await picker().locator('.choice-search input').fill('龙宫')
    await picker().locator('.choice-row').getByText('龙宫', { exact: true }).click()
    await page.getByText('保存记录', { exact: true }).click()
    await page.locator('.role-header').waitFor()
    assert.equal((await read()).roles.find(role => role.id === saved.id).school, '龙宫')
    assert.equal(ledger.roleSummary(await read(), saved.id).total, 0)
    // The optional race picker retains its existing clear action.
    await editRole()
    await group('角色种族（装备换算）').locator('.field').click()
    await picker().getByText('未配置 / 清空', { exact: true }).waitFor()
    await picker().getByText('取消', { exact: true }).click()
    await openSchool()
    await picker().locator('.choice-search input').fill('九黎')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: fileURLToPath(new URL('school-' + width + '.png', images)) })
    await picker().locator('.choice-row').getByText('九黎城', { exact: true }).click()
    await page.locator('uni-page-head .uni-page-head-hd').click()
    await page.getByText('保留草稿并返回', { exact: true }).click()
    await page.locator('.role-header').waitFor()
    assert.equal((await read()).roles.find(role => role.id === saved.id).school, '龙宫')
    await editRole()
    await page.getByText('恢复草稿', { exact: true }).click()
    await page.waitForFunction(() => [...document.querySelectorAll('.field-group')].some(el => el.textContent.includes('门派 *') && el.textContent.includes('九黎城')))
    assert.match(await school().innerText(), /九黎城/)
    assert.equal(await group('角色名称 *').locator('input').inputValue(), '门派验证角色')
    await page.getByText('保存记录', { exact: true }).click()
    await page.locator('.role-header').waitFor()
    assert.equal((await read()).roles.find(role => role.id === saved.id).school, '九黎城')
    await context.close()
    console.log('PASS ' + width + 'px: 所有门派搜索选择、列表末项、当前值、取消、空搜索、新建/编辑保存、门派草稿恢复与原资产保留')
  }
  assert.deepEqual(failures, [])
} finally { await browser.close() }
